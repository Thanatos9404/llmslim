// Renders the LLMSlim mark as ASCII art for the page backdrops (src/components/site/backdrop-art.ts).
// Usage, from web/: node scripts/brand/ascii.mjs
import { writeFileSync } from "node:fs"
import sharp from "sharp"

const COLS = 92
const ROWS = 30 // a monospace cell is about twice as tall as it is wide, so rows ≈ cols × (height / width) / 2
const RAMP = " .:-=+*%#@"

const { data, info } = await sharp("public/brand/llmslim-mark-white.svg", { density: 600 })
  .flatten({ background: "#000000" })
  .resize(COLS, ROWS, { fit: "fill" })
  .greyscale()
  .raw()
  .toBuffer({ resolveWithObject: true })

const lines = []
for (let y = 0; y < info.height; y++) {
  let line = ""
  for (let x = 0; x < info.width; x++) {
    const level = data[y * info.width + x] / 255
    line += RAMP[Math.min(RAMP.length - 1, Math.round(level * (RAMP.length - 1)))]
  }
  lines.push(line.replace(/\s+$/, ""))
}
while (lines.length && !lines[0].trim()) lines.shift()
while (lines.length && !lines[lines.length - 1].trim()) lines.pop()

const art = lines.join("\n")
writeFileSync(
  "src/components/site/backdrop-art.ts",
  `// Generated by scripts/brand/ascii.mjs from public/brand/llmslim-mark-white.svg. Do not edit by hand.\n` +
    `export const MARK_ASCII = ${JSON.stringify(art)}\n`,
)
console.log(art)
