def load_phase4_5_cases() -> List[Dict[str, Any]]:
    cases = []
    for index, row in enumerate(QUERY_ROWS):
        tool_ids, language, query = row.split("|", 2)
        identifiers = [] if tool_ids == "-" else tool_ids.split(",")
        categories = [
            next(category for identifier, _, _, category in TOOL_ROWS if identifier == tool_id)
            for tool_id in identifiers
        ]
        cases.append(
            {
                "id": "authored-%03d" % (index + 1),
                "query": query,
                "required": [
                    category + "/" + tool_id.replace(".", "_")
                    for tool_id, category in zip(identifiers, categories)
                ],
                "language": language,
                "category": categories[0]
                if len(set(categories)) == 1 and categories
                else ("no_tool" if not categories else "cross_domain"),
                "class": "no_tool"
                if not identifiers
                else ("multi_tool" if len(identifiers) > 1 else "single_tool"),
                "provenance": "REPOSITORY_AUTHORED",
            }
        )
    return cases
